    private void limpiar(){
        txtValor.setText("");
        txtVehiculo.setText("");
    }
    public void agregarVehiculo(){
        try (Connection con = DriverManager.getConnection(conexion.getUrl(),
                conexion.getUsername(), conexion.getPassword())) {
            PreparedStatement pstm = con.prepareCall("call agregarVehiculo(?,?)");
            String nombre = txtVehiculo.getText();
            int valor = Integer.parseInt(txtValor.getText());
            pstm.setString(1, nombre);
            pstm.setInt(2, valor);
            pstm.execute();
            JOptionPane.showMessageDialog(this, "Vehiculo Agregado con exito");
            limpiar();
        }catch(SQLException e){
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    public void actualizar(){
        try (Connection con = DriverManager.getConnection(conexion.getUrl(),
                conexion.getUsername(), conexion.getPassword())) {
            int precio = Integer.parseInt(txtValor.getText());
            PreparedStatement pstm = con.prepareCall("call actualizarPrecios(?,?)");
            pstm.setInt(1, id);
            pstm.setInt(2, precio);
            int rowAffected = pstm.executeUpdate();
            if (rowAffected > 0) {
                JOptionPane.showMessageDialog(this, "Datos actualizados");
            }else{
                JOptionPane.showMessageDialog(this, "No se pudo realizar la actualizacion");
            }
            mostrarInfo();
            limpiar();
            pos= -1 ;
            btnAgregar.setEnabled(true);
            btnActualizar.setEnabled(false);
        }catch(SQLException e){
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    
    public void mostrarInfo() {
        try (Connection con = DriverManager.getConnection(conexion.getUrl(),
                conexion.getUsername(), conexion.getPassword())) {
            DefaultTableModel modelo = new DefaultTableModel();
            ListaVehiculo.clear();

            Statement stm = con.createStatement();
            String query = "call mostrarVehiculos();";
            ResultSet rs = stm.executeQuery(query);
            
            ResultSetMetaData rsmt = rs.getMetaData();
            for (int i = 1; i <= rsmt.getColumnCount(); i++) {
                modelo.addColumn(rsmt.getColumnLabel(i));
            }

            while (rs.next()) {
                String tipoVehiculo = rs.getString("tipoVehiculo");
                int id = rs.getInt("id");
                int valor = rs.getInt("valor");
                ListaVehiculo.add(new Vehiculos(id, tipoVehiculo, valor));
                Object[] filas = new Object[rsmt.getColumnCount()];
                for (int i = 1; i <= rsmt.getColumnCount(); i++) {
                    filas[i-1] = rs.getObject(i);
                }
                modelo.addRow(filas);
                
            }
            tabeVehiculos.setModel(modelo);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    
    
